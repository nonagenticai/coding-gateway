#!/usr/bin/env python3
"""Regenerate ``tests/data/coding_operation_index.json`` from an aggregated spec.

The drift test in ``tests/unit/test_operation_metadata.py`` needs to know which
operationIds the *fleet* publishes. The gateway cannot compute that alone -- the
aggregated spec is assembled from every backend at runtime -- so the id/method
index is vendored as a fixture and refreshed deliberately.

Only ``(method, path, operationId)`` is kept. The full spec is ~1 MB of schemas
the test never reads; an index is ~40x smaller and reviewable in a diff.

Usage::

    python scripts/refresh_operation_index.py https://gateway.example.com/openapi.json
    python scripts/refresh_operation_index.py path/to/openapi.json [source-label]

``source-label`` overrides what is recorded as provenance, so a spec read from a
local checkout can still record where it canonically came from instead of one
machine's absolute path.

Refresh it whenever an operation is added, removed or renamed anywhere in the
fleet -- the same moment ``operation_metadata.py`` needs updating.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

_METHODS = {"get", "post", "put", "patch", "delete", "options", "head", "trace"}
_OUT = Path(__file__).resolve().parent.parent / "tests" / "data" / "coding_operation_index.json"


def _load(source: str) -> tuple[bytes, str]:
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source) as fh:  # noqa: S310 - operator-supplied URL
            return fh.read(), source
    return Path(source).read_bytes(), source


def build_index(raw: bytes, source: str) -> dict:
    """Reduce a full OpenAPI spec to the operation index the drift tests read.

    Deliberately records no digest of the source spec. A bare sha256 is a
    ``Hex High Entropy String`` to detect-secrets, so it reds the CI secret gate
    on first commit and again on every refresh -- a permanent false-positive
    tax for provenance that ``source`` plus ``operation_count`` already carry.
    Integrity of the *operation set* is checked directly instead: point
    ``CODING_OPENAPI_SPEC`` at a live gateway and the same tests run against it.
    """
    spec = json.loads(raw)
    operations = [
        {"method": method, "path": path, "operationId": op["operationId"]}
        for path, item in (spec.get("paths") or {}).items()
        if isinstance(item, dict)
        for method, op in item.items()
        if method in _METHODS and isinstance(op, dict) and isinstance(op.get("operationId"), str)
    ]
    operations.sort(key=lambda o: (o["operationId"], o["method"], o["path"]))
    return {
        "_comment": (
            "Generated by scripts/refresh_operation_index.py -- do not hand-edit. "
            "Method/path/operationId only; see that script for why."
        ),
        "source": source,
        "operation_count": len(operations),
        "operations": operations,
    }


def main(argv: list[str]) -> int:
    if len(argv) not in (2, 3):
        print(__doc__)
        return 2
    raw, source = _load(argv[1])
    if len(argv) == 3:
        source = argv[2]
    index = build_index(raw, source)
    _OUT.write_text(json.dumps(index, indent=2, sort_keys=False) + "\n")
    print(f"wrote {_OUT} — {index['operation_count']} operations from {source}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
