"""What one non-Python file defines, asked of coding-analysis, and matched here.

The reference endpoints answer Python by grepping ``def``/``class`` syntax. Every
other language the coding app supports is answered by sending the file's
content -- read from the CALLER's workspace, never resolved by container name
upstream -- to coding-analysis ``POST /api/analysis/symbols``, which walks the
tree-sitter tree and reports ``{name, kind, line, end_line, parent}`` per
definition. This module is the client for that call and the matching rules
applied to its answer.

The rules exist to keep three answers apart (George 2026-10-11):

- ``True``  -- a definition of the claimed kind is in the file;
- ``False`` -- the file was parsed cleanly and nothing of that name is in it;
- ``None``  -- it could not be established: the upstream failed or timed out,
  the parse hit an error that could hide a definition, the name exists but as
  a different kind (a variable, a namespace, a property), the file is a C/C++
  header (the extractor does not report a prototype whose parameters are all
  bare type names, ``Foo make(Bar);``), or one of the cases below.

INHERITANCE AND RE-EXPORTS (coding-analysis ``bases`` / ``impls`` / ``reexports``).
``match_symbol`` stays pure: when the answer depends on another file it returns
``valid=None`` with a ``pending`` follow-up, which ``services.symbol_walk``
resolves inside the same workspace:

  * a dotted ``Owner.member`` whose owner TYPE is in the file without the
    member -> ``Inherit``: the owner's ``bases`` (and, Rust, the traits of every
    ``impl Trait for Owner`` in the file -- trait default methods) are located
    and checked, at most 5 hops. Found -> ``True`` ("inherited from"). Every
    base resolved in the workspace and the member absent everywhere -> ``False``
    -- unless a ``blocker`` applies: Go (methods may live in any file of the
    package) and Rust (``impl`` blocks anywhere in the crate) never; C# never
    (extension methods ``M(this Owner o)`` and ``partial`` types add members
    from any file -- a member FOUND is still ``True``); JS/TS ``this.m =`` /
    ``Owner.prototype.m`` / ``Owner.m =`` assignments or an ``interface`` owner
    (declarations merge), and -- searched workspace-wide by the walk -- an
    ``interface Owner`` / ``Owner.prototype.m`` / ``Owner.m =`` in ANY file
    (declaration merging, module augmentation); Python: a ``Owner.m = ...`` /
    ``setattr(Owner`` anywhere in the workspace (monkeypatching, checked by the
    router);
    an ``enum`` owner (members are not extracted); a parse error, a header, or
    a C++ file mentioning the member as a word (macros). Any base that cannot
    be resolved in the workspace (external, qualified ``pkg.Base``, imported
    from a package, ambiguous) -> ``None`` naming the base. A base is located
    only with PROOF that the name as written binds to that file (see
    ``services.symbol_walk``): never by "the one workspace file defining a type
    of that name".
  * JS/TS, Python ``__init__``, Rust: the name is absent as a definition but
    listed in ``reexports`` (by name or alias, else via ``export *``) ->
    ``Reexport``: ``from_module`` is resolved to the target file (relative
    specifiers only for JS/TS; Python relative or in-repo absolute modules;
    Rust ``crate``/``self``/``super``/child-module paths), at most 3 hops.
    Found -> ``True`` ("re-exported via"); every hop resolved and absent ->
    ``False``; any unresolved hop (a package, a path alias) -> ``None``.
    ``export =`` / ``module.exports = require(`` stay ``None``.
  * Rust, C, C++ outside a followed re-export: the name appears as a word in
    the file -- it may be generated by a macro, and macro expansion is not
    analysed.

  A body WITHOUT the ``reexports`` key comes from a coding-analysis that
  predates these fields: every case above is then ``None`` as before
  (bases not checked; a JS/TS name that is imported, listed in an
  ``export { ... }`` or re-exported wholesale is a possible re-export).

  Python, Go, Java, C# and JS/TS outside these cases keep a definite ``False``
  for a clean-parse absence.

KINDS for a class/type reference: ``CLASS_KINDS`` plus the C++20 ``concept``
(``CLASS_REFERENCE_KINDS``). A concept is a named constraint, a type-level
entity a reference can name, but it has no members, so it is NOT an owner kind
(``Concept.x`` never finds an owner).

A wrong ``False`` sends a correct card back; a wrong ``True`` lets an invented
symbol through. So ``False`` is only ever the clean-parse, name-absent case,
outside every exception above.

Kinds (coding-analysis ``processing/symbols.py``): function, method,
const_function, class, interface, type, enum, struct, trait, namespace, module,
record, property, event, indexer, operator, macro, field, delegate, variable,
concept.
Its documented gaps (enum members, instance attributes, names bound inside
function bodies, macro-generated definitions) are why an absence of a MEMBER
kind is never turned into ``False`` here on its own.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field
from typing import Any

import httpx

from clients.outbound_identity import identity_headers
from config.settings import get_settings
from services.container_workspace import LANGUAGE_EXTENSIONS

logger = logging.getLogger(__name__)

SYMBOLS_PATH = "/api/analysis/symbols"
SYMBOLS_TIMEOUT_SECONDS = 30.0
MAX_CODE_BYTES = 2 * 1024 * 1024

FUNCTION_KINDS = frozenset(
    {"function", "method", "const_function", "operator", "macro", "delegate"}
)
CLASS_KINDS = frozenset({"class", "interface", "struct", "trait", "enum", "record", "type"})
# A class/type REFERENCE also accepts a C++20 concept; an owner never is one.
CLASS_REFERENCE_KINDS = CLASS_KINDS | {"concept"}
# Members that satisfy a DOTTED function reference (``Owner.prop``) only.
MEMBER_KINDS = frozenset({"property", "field", "event", "indexer"})

# C/C++ headers: a prototype whose parameters are all bare type names is not
# reported by the extractor, so absence there is never ``False``.
HEADER_EXTENSIONS: tuple[str, ...] = (".h", ".hpp", ".hh", ".hxx", ".h++")

# Languages whose files can re-export a name they do not define (barrels).
REEXPORT_LANGUAGES = frozenset({"javascript", "typescript"})
# Languages whose ``reexports`` are followed (Python only in a package __init__).
REEXPORT_FOLLOW_LANGUAGES = frozenset({"javascript", "typescript", "python", "rust"})
# CommonJS exports are not in ``reexports``: an imported name may leave through them.
_COMMONJS_EXPORTS = re.compile(r"\bmodule\.exports\b|\bexports\.[\w$]")
_WHOLESALE_UNFOLLOWED = re.compile(r"\bexport\s*=(?!=)|\bmodule\.exports\s*=\s*require\s*\(")
# Languages whose macros can generate a definition the extractor never sees.
MACRO_LANGUAGES = frozenset({"rust", "cpp"})

_WHOLESALE_REEXPORT = re.compile(
    r"\bexport\s*\*\s*(?:as\s+[\w$]+\s+)?from\b"
    r"|\bexport\s*=(?!=)"
    r"|\bmodule\.exports\s*=\s*require\s*\("
)


def symbol_language(path: str) -> str | None:
    """The coding-analysis language for *path*'s extension, or ``None`` if unsupported."""
    lowered = path.lower()
    for language, extensions in LANGUAGE_EXTENSIONS.items():
        if lowered.endswith(extensions):
            return language
    return None


def is_header(path: str) -> bool:
    return path.lower().endswith(HEADER_EXTENSIONS)


@dataclass
class SymbolsFetch:
    """The upstream answer, or why there is none (``body is None``)."""

    body: dict[str, Any] | None
    error: str | None = None


@dataclass
class Inherit:
    """Follow-up: *owner* is a type in *path* without *member*; check its bases."""

    path: str
    content: str
    body: dict[str, Any]
    owner: str
    member: str
    bases: list[str]
    traits: list[str]  # Rust: traits of ``impl Trait for Owner`` in this file
    blockers: list[str]  # why an absence on every base still cannot be False


@dataclass
class Reexport:
    """Follow-up: *word* is not defined in *path* but re-exported from elsewhere."""

    path: str
    content: str
    word: str
    entries: list[dict[str, Any]]  # the matching ``reexports`` entries
    blockers: list[str]


@dataclass
class FileMatch:
    """One file's verdict for one name."""

    verdict: bool | None
    note: str | None = None
    definitions: list[dict[str, Any]] = field(default_factory=list)
    # Set only with verdict None: the walk (``services.symbol_walk``) that decides it.
    pending: Inherit | Reexport | None = None


async def fetch_symbols(code: str, file_path: str, tenant_id: str | None) -> SymbolsFetch:
    """POST *code* to coding-analysis ``/api/analysis/symbols``.

    Any non-200, a timeout, a transport error, a body of the wrong shape or
    ``parsed: false`` is returned as an error -- the caller reports it as
    "not computed", never as "absent".
    """
    if len(code.encode("utf-8")) > MAX_CODE_BYTES:
        return SymbolsFetch(None, f"'{file_path}' is over the 2 MiB symbol-extraction limit")
    # Imported here for the reason given in ``container_workspace.containers_post``:
    # importing ``routers.proxy`` at module scope freezes its route table.
    from routers.proxy import get_proxy_client

    settings = get_settings()
    base = (settings.analysis_url or "").rstrip("/")
    if not base:
        return SymbolsFetch(None, "ANALYSIS_URL is not configured on this gateway")
    try:
        client = await get_proxy_client()
        response = await client.post(
            f"{base}{SYMBOLS_PATH}",
            json={"code": code, "file_path": file_path},
            headers=identity_headers(tenant_id),
            timeout=httpx.Timeout(SYMBOLS_TIMEOUT_SECONDS),
        )
    except httpx.TimeoutException:
        return SymbolsFetch(None, "coding-analysis symbol extraction timed out")
    except httpx.HTTPError as exc:
        return SymbolsFetch(None, f"coding-analysis is unreachable: {exc}")
    if response.status_code != 200:
        return SymbolsFetch(
            None,
            f"coding-analysis symbol extraction answered {response.status_code}: "
            f"{response.text[:200]}",
        )
    try:
        body = response.json()
    except ValueError:
        return SymbolsFetch(None, "coding-analysis returned a non-JSON symbols body")
    if (
        not isinstance(body, dict)
        or body.get("parsed") is not True
        or not isinstance(body.get("symbols"), list)
    ):
        return SymbolsFetch(None, "coding-analysis returned no parsed symbol list")
    return SymbolsFetch(body)


def _accepted_kinds(kind: str, dotted: bool) -> frozenset[str]:
    if kind == "class":
        return CLASS_KINDS if dotted else CLASS_REFERENCE_KINDS
    return FUNCTION_KINDS | MEMBER_KINDS if dotted else FUNCTION_KINDS


def _definition(path: str, sym: dict[str, Any]) -> dict[str, Any]:
    return {
        "file": path,
        "line": sym.get("line"),
        "kind": sym.get("kind"),
        "parent": sym.get("parent"),
        "name": sym.get("name"),
    }


def _reexport_note(body: dict[str, Any], content: str, word: str, path: str) -> str | None:
    """Why *path* (JS/TS) may re-export *word*, or ``None`` if it does not."""
    for imp in body.get("imports") or []:
        if isinstance(imp, dict) and word in (imp.get("names") or []):
            why = f"imports '{word}' (from '{imp.get('module')}')"
            break
    else:
        if re.search(rf"\bexport\s*\{{[^}}]*\b{re.escape(word)}\b", content):
            why = f"lists '{word}' in an `export {{ ... }}`"
        elif m := _WHOLESALE_REEXPORT.search(content):
            why = f"re-exports wholesale (`{m.group(0).strip()}`)"
        else:
            return None
    return (
        f"'{word}' is not defined in {path}, but the file {why}, so it may be a re-export "
        "(barrel) of a definition elsewhere; re-exports are not followed, so absence is NOT "
        "computed (valid=null)."
    )


def _absence_exception(body: dict[str, Any], content: str, word: str, path: str) -> str | None:
    """The language-specific reason an absence of *word* in *path* is not ``False``."""
    language = symbol_language(path)
    if language in REEXPORT_LANGUAGES:
        return _reexport_note(body, content, word, path)
    if language in MACRO_LANGUAGES and re.search(rf"\b{re.escape(word)}\b", content):
        return (
            f"'{word}' is not among the definitions extracted from {path}, but it appears "
            "there as a word: it may be generated by a macro; macro expansion is not "
            "analysed, so absence is NOT computed (valid=null)."
        )
    return None


def has_walk_fields(body: dict[str, Any]) -> bool:
    """The upstream reports ``bases`` / ``impls`` / ``reexports`` (always lists there)."""
    return isinstance(body.get("reexports"), list)


def simple_type_name(name: str) -> str:
    """``Foo<T>`` / ``&Foo`` -> ``Foo`` (qualification kept)."""
    return re.sub(r"<.*$", "", name.strip().lstrip("&*")).strip()


def _member_blockers(
    body: dict[str, Any], content: str, owner: str, member: str, path: str, types: list[dict]
) -> list[str]:
    """Why ``member`` absent from *owner* and from all its bases is still not ``False``."""
    language = symbol_language(path)
    out: list[str] = []
    o, m = re.escape(owner), re.escape(member)
    if language == "go":
        out.append("Go methods can be declared in any file of the package")
    if language == "rust":
        out.append("Rust `impl` blocks can be anywhere in the crate")
    if language == "c_sharp":
        out.append(
            "C# extension methods (`static ... M(this Owner o)` in any static class) and "
            "partial types can add members from any file"
        )
    if language in REEXPORT_LANGUAGES:
        if re.search(rf"\bthis\.{m}\s*=(?!=)|\b{o}\.prototype\.{m}\b|\b{o}\.{m}\s*=(?!=)", content):
            out.append(f"'{member}' is assigned outside a class body (`this.`/prototype/static)")
        if any(t.get("kind") == "interface" for t in types):
            out.append(f"'{owner}' is a TS interface (declarations merge across files)")
    if any(t.get("kind") == "type" for t in types):
        # `type T = Base & {...}` / `type T = string`: members come from the
        # aliased type, which the extractor does not report as bases.
        out.append(f"'{owner}' is a type alias (its members come from the aliased type)")
    if any(t.get("kind") == "enum" for t in types):
        out.append("enum members are not extracted")
    if body.get("parse_error_line"):
        out.append(f"{path} has a parse error at line {body.get('parse_error_line')}")
    if is_header(path):
        out.append(f"{path} is a C/C++ header (prototypes may be unreported)")
    elif language == "cpp" and re.search(rf"\b{m}\b", content):
        out.append(f"'{member}' appears as a word in {path} (it may be macro-generated)")
    return out


def _inherit(
    body: dict[str, Any], content: str, owner: str, member: str, path: str, symbols: list[dict]
) -> Inherit:
    types = [s for s in symbols if s.get("name") == owner and s.get("kind") in CLASS_KINDS]
    bases: list[str] = []
    for t in types:
        for b in t.get("bases") or []:
            if isinstance(b, str) and b and b not in bases:
                bases.append(b)
    traits: list[str] = []
    for impl in body.get("impls") or []:
        if isinstance(impl, dict) and simple_type_name(str(impl.get("type") or "")) == owner:
            trait = impl.get("trait")
            if isinstance(trait, str) and trait and trait not in traits:
                traits.append(trait)
    blockers = _member_blockers(body, content, owner, member, path, types)
    return Inherit(path, content, body, owner, member, bases, traits, blockers)


def _reexport_pending(body: dict[str, Any], content: str, word: str, path: str) -> FileMatch | None:
    """The re-export follow-up for *word* in *path*, a null, or ``None`` (not re-exported)."""
    entries = [e for e in body.get("reexports") or [] if isinstance(e, dict)]
    named = [
        e for e in entries if e.get("name") != "*" and (e.get("alias") or e.get("name")) == word
    ]
    namespace = [e for e in entries if e.get("name") == "*" and e.get("alias") == word]
    star = [e for e in entries if e.get("name") == "*" and not e.get("alias")]
    blockers: list[str] = []
    if symbol_language(path) in REEXPORT_LANGUAGES and (m := _WHOLESALE_UNFOLLOWED.search(content)):
        blockers.append(f"{path} also re-exports wholesale (`{m.group(0).strip()}`), not followed")
    if namespace and not named:
        return FileMatch(
            None,
            f"'{word}' is re-exported by {path} as a namespace (`export * as {word}`), not as a "
            "definition of the claimed kind (valid=null).",
        )
    chosen = named or star
    if not chosen:
        if blockers:
            return FileMatch(
                None, f"'{word}' is not defined in {path}, but {blockers[0]} (valid=null)."
            )
        return None
    if symbol_language(path) == "rust":
        lines = {e.get("line") for e in chosen}
        rest = "\n".join(t for i, t in enumerate(content.splitlines(), 1) if i not in lines)
        if re.search(rf"\b{re.escape(word)}\b", rest):
            blockers.append(
                f"'{word}' also appears as a word in {path} outside its `pub use` "
                "(it may be macro-generated)"
            )
    note = (
        f"'{word}' is not defined in {path}, but the file re-exports it "
        f"({', '.join(str(e.get('from_module')) for e in chosen)}); the re-export was not "
        "followed (valid=null)."
    )
    return FileMatch(None, note, pending=Reexport(path, content, word, chosen, blockers))


def match_symbol(body: dict[str, Any], name: str, kind: str, path: str, content: str) -> FileMatch:
    """Is *name* defined in *path* as a *kind* (``"function"`` or ``"class"``)?

    *content* is the file text the symbols were extracted from (needed for the
    re-export and macro exceptions). A dotted ``Owner.member`` requires
    ``member`` with ``parent == Owner`` (the last owner segment). See the module
    docstring for when the answer is null.
    """
    symbols = [s for s in body.get("symbols") or [] if isinstance(s, dict)]
    *owners, member = name.split(".")
    owner = owners[-1] if owners else None
    accepted = _accepted_kinds(kind, owner is not None)
    named = [s for s in symbols if s.get("name") == member]
    noun = "function/method" if kind == "function" else "class/type"

    if owner is None:
        hits = [s for s in named if s.get("kind") in accepted]
        if hits:
            return FileMatch(True, None, [_definition(path, s) for s in hits])
        if named:
            kinds = sorted({str(s.get("kind")) for s in named})
            return FileMatch(
                None,
                f"'{name}' is defined in {path} as a {'/'.join(kinds)}, not as a {noun}; "
                "the name exists, so this is not reported as absent (valid=null).",
            )
        absent_word = name
    else:
        on_owner = [s for s in named if s.get("parent") == owner]
        hits = [s for s in on_owner if s.get("kind") in accepted]
        if hits:
            return FileMatch(True, None, [_definition(path, s) for s in hits])
        if on_owner:
            kinds = sorted({str(s.get("kind")) for s in on_owner})
            return FileMatch(
                None,
                f"'{name}' is defined in {path} as a {'/'.join(kinds)} of '{owner}', not as a "
                f"{noun} (valid=null).",
            )
        owner_is_type = any(
            s.get("name") == owner and s.get("kind") in CLASS_KINDS for s in symbols
        )
        if owner_is_type and has_walk_fields(body):
            return FileMatch(
                None,
                f"'{owner}' is a type defined in {path}, but no {noun} '{member}' is defined "
                f"with '{owner}' as its parent there; its bases were not followed "
                "(valid=null).",
                pending=_inherit(body, content, owner, member, path, symbols),
            )
        if owner_is_type:
            return FileMatch(
                None,
                f"'{owner}' is a type defined in {path}, but no {noun} '{member}' is defined "
                f"with '{owner}' as its parent there. It may be inherited from a base type, "
                "embedded (a promoted field/method of an embedded struct), or implemented "
                "elsewhere (another impl block, partial class, extension or prototype "
                "assignment); bases were not checked, so absence is NOT computed (valid=null).",
            )
        if named:
            return FileMatch(
                None,
                f"'{member}' is defined in {path}, but '{owner}' is not a type defined there "
                "(it may be a namespace, module or package qualifier, whose membership the "
                "symbol extraction does not record), so the owner was NOT established "
                "(valid=null).",
            )
        absent_word = owner

    parse_error_line = body.get("parse_error_line")
    if parse_error_line:
        return FileMatch(
            None,
            f"'{name}' was not found in {path}, but the file has a parse error at line "
            f"{parse_error_line} that can hide a definition, so absence is NOT computed "
            "(valid=null).",
        )
    if is_header(path):
        return FileMatch(
            None,
            f"'{name}' was not found in the C/C++ header {path}, but the symbol extraction "
            "does not report a prototype whose parameters are all bare type names "
            "(`Foo make(Bar);`), so absence in a header is NOT computed (valid=null).",
        )
    if has_walk_fields(body):
        if symbol_language(path) in REEXPORT_FOLLOW_LANGUAGES:
            followed = _reexport_pending(body, content, absent_word, path)
            if followed is not None:
                return followed
        if symbol_language(path) in REEXPORT_LANGUAGES and not _COMMONJS_EXPORTS.search(content):
            # Not re-exported: an imported-but-not-exported name is not reachable here.
            exception = None
        else:
            exception = _absence_exception(body, content, absent_word, path)
    else:
        exception = _absence_exception(body, content, absent_word, path)
    if exception:
        return FileMatch(None, exception)
    if owner is not None:
        return FileMatch(
            False,
            f"No type '{owner}' is defined in {path}, so no {noun} '{name}' is defined there.",
        )
    return FileMatch(False, f"No {noun} '{name}' is defined in {path}.")
